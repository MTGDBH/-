assert.match(html, /subject_user_id/);
assert.match(html, /measurement_condition/);
assert.match(css, /\.discovery-tabs/);
assert.match(css, /\.answer-options button:focus-visible/);
assert.match(css, /@media\(max-width:800px\)/);
assert.match(css, /\.axis-grid/);
assert.match(css, /\.clinical-band/);
assert.match(css, /\.peer-median/);
assert.match(html, /function niceScale/);
